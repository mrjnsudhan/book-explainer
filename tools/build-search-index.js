// Builds book-explainer/search-index.js: the text of every chapter of every explainer on the shelf,
// read from the rendered pages (some explainers draw their chapters with JavaScript).
// Run from the shelf folder: node tools/build-search-index.js   (needs Playwright + Chromium)
// Keyed by book title (as in BOOKS in index.html), so it survives the shelf's url rewriting for artifacts.
const { chromium } = require('playwright'); const fs = require('fs'); const path = require('path');
const root = path.resolve(process.argv[2] || path.join(__dirname, '..'));
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const books = [];
for (const chunk of html.split(/\n\s*\{ shelf:/).slice(1)) {
  const t = chunk.match(/title:'((?:\\'|[^'])*)'/), u = chunk.match(/url:'explainers\/([\w-]+)\.html'/);
  if (t && u) books.push({ title: t[1].replace(/\\'/g, "'"), slug: u[1] });
}
const KIND = { law: 'Law', ws: 'Workshop', ch: 'Chapter' };
(async () => {
  const b = await chromium.launch(); const out = {}; let n = 0;
  for (const { title, slug } of books) {
    const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
    await p.goto('file://' + path.join(root, 'explainers', slug + '.html')); await p.waitForTimeout(300);
    const chs = await p.$$eval('section.ch[id], section.law[id], section.ws[id]', S => S.map(s => {
      const h = s.querySelector('h2,h3');
      return [s.id, s.dataset.n || '', (h ? h.innerText : '').replace(/\s+/g, ' ').trim(), s.innerText.replace(/\s+/g, ' ').trim()];
    }));
    await p.close();
    out[title] = chs.map(([id, num, t, txt]) => {
      // Only laws and workshops get a number label: chapter numbering differs from book to book (intros etc.).
      const kind = slug === 'art-of-war' ? '' : KIND[id.replace(/\d.*$/, '')] || '';
      const at = t ? txt.indexOf(t) : -1;  // drop the eyebrow and heading so snippets start with the content
      return [id, kind && kind !== 'Chapter' ? `${kind} ${String(num).replace(/^w/, '')}` : '', t, at >= 0 ? txt.slice(at + t.length).trim() : txt];
    });
    n += chs.length; if (!chs.length) console.warn('NO CHAPTERS:', slug);
  }
  await b.close();
  const js = '/* Generated by tools/build-search-index.js. Do not edit by hand. */\nwindow.SEARCH_INDEX=' + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(root, 'search-index.js'), js);
  console.log(`indexed ${books.length} books, ${n} chapters, ${(js.length / 1024).toFixed(0)} KB`);
})();
